# ============================================================
# 基础工具函数
# ============================================================

def clamp(value, minimum=0.0, maximum=100.0):
    return max(
        minimum,
        min(value, maximum)
    )


def gaussian_unit(
    value,
    optimal,
    sigma
):
    return math.exp(
        -((value - optimal) ** 2)
        / (2 * sigma ** 2)
    )


def logistic_unit(
    value,
    midpoint,
    steepness
):
    return 1.0 / (
        1.0
        + math.exp(
            -steepness
            * (value - midpoint)
        )
    )


def geometric_mean(values):
    positive_values = [
        max(float(v), 1e-6)
        for v in values
    ]

    log_mean = (
        sum(
            math.log(v)
            for v in positive_values
        )
        / len(positive_values)
    )

    return math.exp(log_mean)


# ============================================================
# I_GZA
#
# Zhou et al. (2022):
#
# I_GZA =
# [ Σ(N_i × AP_i × PE_i × FD_i × S_i × H_i) ]
# / (378 × S_T)
#
# N  = individual number
# AP = allergenic potential
# PE = pollen emission
# FD = flowering duration
# S  = crown projection area
# H  = canopy height
# ST = assessment-unit area (m²)
#
# canonical_igza:
#   严格按总园区面积作为 ST。
#
# effective_green_igza:
#   BJ Pollenix 扩展指标，把用户定义的“有效绿地面积”
#   作为局部植被源面积进行归一化。
#   它不是 Zhou et al. 原文的标准 I_GZA，故记作 I_GZA*。
# ============================================================

def igza_component(
    tree: AllergenicTree
):
    return (
        tree.count
        * tree.allergenic_potential
        * tree.pollen_emission
        * tree.flowering_duration
        * tree.crown_area
        * tree.canopy_height
    )


def calculate_igza(
    park: ParkProfile,
    area_ha: float
):
    numerator = sum(
        igza_component(tree)
        for tree in park.trees
    )

    area_m2 = (
        area_ha
        * 10000.0
    )

    return (
        numerator
        / (
            378.0
            * area_m2
        )
    )


def species_hazard_shares(
    park: ParkProfile
):
    raw = {
        tree.chinese_name:
        igza_component(tree)
        for tree in park.trees
    }

    total = max(
        sum(raw.values()),
        1e-9
    )

    return {
        name:
        100.0 * value / total
        for name, value in raw.items()
    }


