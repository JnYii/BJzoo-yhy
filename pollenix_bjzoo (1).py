def vegetation_score(
    effective_igza
):
    """
    以颐和园 I_GZA* 作为 100 分内部参考。
    这只是 BJ Pollenix 的跨公园相对比较尺度，
    不是医学概率或 Zhou et al. 的风险分界。
    """
    ratio = (
        effective_igza
        / max(
            SUMMER_PALACE_EFFECTIVE_IGZA,
            1e-9
        )
    )

    return clamp(
        ratio * 100.0
    )


# ============================================================
# 木本花粉浓度分级
#
# Zhou et al. (2022) Table 1:
# Woody pollen:
# Level 1 <= 100
# Level 2 101-250
# Level 3 251-400
# Level 4 401-800
# Level 5 > 800
# Unit: granule / 1000 mm²
#
# 这里把五个等级线性映射到 20/40/60/80/100，
# 仅用于 dashboard 的 0-100 内部显示。
# ============================================================

def woody_pollen_level(
    pollen_density
):
    if pollen_density <= 100:
        return 1
    elif pollen_density <= 250:
        return 2
    elif pollen_density <= 400:
        return 3
    elif pollen_density <= 800:
        return 4
    else:
        return 5


def pollen_score(
    pollen_density
):
    level = woody_pollen_level(
        pollen_density
    )

    return (
        level * 20.0
    )


# ============================================================
# 春季木本花粉季节因子
#
# 颐和园论文实证重点是春季 3-5 月。
# 为了让日期连续变化，用 4 月为中心做平滑 Gaussian。
#
# peak=4.0, sigma=0.85 是 BJ Pollenix 平滑参数，
# 不是 Zhou et al. 原论文回归系数。
# ============================================================

def circular_month_distance(
    month,
    peak_month
):
    diff = abs(
        month - peak_month
    )

    return min(
        diff,
        12 - diff
    )


def spring_season_factor(
    month
):
    distance = (
        circular_month_distance(
            month,
            4.0
        )
    )

    factor = (
        0.03
        + 0.97
        * math.exp(
            -(distance ** 2)
            / (
                2
                * 0.85 ** 2
            )
        )
    )

    return min(
        max(factor, 0.0),
        1.0
    )


# ============================================================
# 气象动态层
#
# 以下方向由北京花粉-气象研究支持：
# - 中等风速利于局地悬浮/传播，过大风速后局地浓度下降；
# - 春季约 5-20°C 更利于高花粉天气；
# - 降雨具有清除作用；
# - 湿度关系非线性；
# - 日照与花粉物候/释放相关。
#
# 具体 sigma / midpoint 是 BJ Pollenix 的平滑实现参数，
# 并非声称为临床阈值。
# ============================================================

def wind_condition_score(
    wind_speed
):
    return (
        100.0
        * gaussian_unit(
            wind_speed,
            optimal=3.0,
            sigma=1.6
        )
    )


def temperature_condition_score(
    temperature
):
    return (
        100.0
        * gaussian_unit(
            temperature,
            optimal=17.0,
            sigma=7.0
        )
    )


def humidity_condition_score(
    humidity
):
    return (
        100.0
        * gaussian_unit(
            humidity,
            optimal=55.0,
            sigma=20.0
        )
    )


def rainfall_condition_score(
    rainfall_48h
):
    # 降雨越多，空气中花粉越容易被清除。
    return (
        100.0
        * math.exp(
            -rainfall_48h
            / 12.0
        )
    )


def sunlight_condition_score(
    sunlight_hours
):
    return (
        100.0
        * logistic_unit(
            sunlight_hours,
            midpoint=6.0,
            steepness=0.35
        )
    )


def pm25_score(
    pm25
):
    return (
        100.0
        * logistic_unit(
            pm25,
            midpoint=75.0,
            steepness=0.03
        )
    )


# ============================================================
# 风险计算
#
# 结构：
# 1) 背景空气花粉等级 -> pollen score
# 2) I_GZA* -> local vegetation score
# 3) 日期 -> spring seasonal activation
# 4) 气象条件 -> weather score
# 5) PM2.5 -> experimental inflammatory modifier
#
# 为减少任意人工权重，天气内部采用几何平均，
# 暴露层采用背景花粉与季节性植被危险度的几何耦合。
#
# PM2.5 最大只提供约 10% 的实验性增强。
# 这仍是 BJ Pollenix 的模型设计，不是已发表临床公式。
# ============================================================

def calculate_risk(
    env: ParkEnvironment,
    park: ParkProfile
):
    date_obj = datetime.strptime(
        env.date,
        "%Y-%m-%d"
    )

    current_month = (
        date_obj.month
        + (date_obj.day - 1)
        / 30.0
    )

    canonical_igza = (
        calculate_igza(
            park,
            park.total_area_ha
        )
    )

    effective_igza = (
        calculate_igza(
            park,
            park.effective_green_area_ha
        )
    )

    V = vegetation_score(
        effective_igza
    )

    season = (
        spring_season_factor(
            current_month
        )
    )

    seasonal_V = (
        V
        * season
    )

    P = pollen_score(
        env.pollen_density
    )

    pollen_level = (
        woody_pollen_level(
            env.pollen_density
        )
    )

    W = wind_condition_score(
        env.wind_speed
    )

    T = temperature_condition_score(
        env.temperature
    )

    H = humidity_condition_score(
        env.humidity
    )

    R = rainfall_condition_score(
        env.rainfall_48h
    )

    S = sunlight_condition_score(
        env.sunlight_hours
    )

    M = pm25_score(
        env.pm25
    )

    weather_score = geometric_mean([
        W,
        T,
        H,
        R,
        S
    ])

    # 背景花粉是直接观测/输入的空气暴露；
    # 植被危险度是局部源强修正。
    exposure_score = geometric_mean([
        max(P, 1.0),
        max(seasonal_V, 1.0)
    ])

    # 天气只调制释放/传播条件，不直接制造花粉。
    base_risk = (
        exposure_score
        * (
            0.60
            + 0.40
            * weather_score
            / 100.0
        )
    )

    # 实验性 PM2.5 炎症增强，最大约 +10%。
    pm_multiplier = (
        1.0
        + 0.10
        * M
        / 100.0
    )

    total_risk = clamp(
        base_risk
        * pm_multiplier
    )

    if total_risk < 20:
        level = "低风险"
        recommendation = "一般可正常活动"
    elif total_risk < 40:
        level = "轻度风险"
        recommendation = "敏感人群可适当缩短户外停留"
    elif total_risk < 60:
        level = "中度风险"
        recommendation = "敏感人群建议减少长时间户外活动"
    elif total_risk < 80:
        level = "高风险"
        recommendation = "过敏人群建议佩戴口罩并减少停留"
    else:
        level = "极高风险"
        recommendation = "过敏人群建议尽量避免长时间进入园区"

    species_shares = (
        species_hazard_shares(
            park
        )
    )

    total_known_trees = sum(
        tree.count
        for tree in park.trees
    )

    tree_density = (
        total_known_trees
        / park.effective_green_area_ha
    )

    factors = {
        "木本花粉": P,
        "局部植被": seasonal_V,
        "风速条件": W,
        "温度条件": T,
        "湿度条件": H,
        "降雨条件": R,
        "日照条件": S,
        "PM2.5": M,
    }

    return {
        "风险评分": round(
            total_risk,
            2
        ),
        "风险等级": level,
        "活动建议": recommendation,
        "木本花粉等级": pollen_level,
        "木本花粉评分": round(
            P,
            2
        ),
        "标准 I_GZA": round(
            canonical_igza,
            4
        ),
        "有效绿地 I_GZA*": round(
            effective_igza,
            4
        ),
        "植被相对评分": round(
            V,
            2
        ),
        "春季活跃系数": round(
            season,
            3
        ),
        "季节性植被评分": round(
            seasonal_V,
            2
        ),
        "天气适宜度": round(
            weather_score,
            2
        ),
        "PM2.5增强系数": round(
            pm_multiplier,
            3
        ),
        "已纳入树木数量": total_known_trees,
        "有效绿地树木密度": round(
            tree_density,
            2
        ),
        "物种危险贡献": {
            k: round(v, 2)
            for k, v
            in species_shares.items()
        },
        "详细指标": {
            k: round(v, 2)
            for k, v
            in factors.items()
        },
    }


